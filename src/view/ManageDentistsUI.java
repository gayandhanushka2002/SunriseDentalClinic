    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
        
        String id = txtId.getText().trim();
        String name = txtName.getText().trim();
        String feeStr = txtFee.getText().trim();

        // Basic Validations
        if (id.isEmpty() || name.isEmpty() || feeStr.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please fill all fields!", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
    double fee = Double.parseDouble(feeStr);

    boolean isSuccess = dentistController.addNewDentist(id, name, fee);
    if (isSuccess) {
        javax.swing.JOptionPane.showMessageDialog(this, "Dentist added successfully!", "Success", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        // Clear text boxes
        txtId.setText(""); 
        txtName.setText(""); 
        txtFee.setText("");
        // Refresh table
        loadTableData();
        } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Failed to add. Dentist ID might already exist.", "Database Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Consultation Fee must be a valid number!", "Input Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSaveActionPerformed

