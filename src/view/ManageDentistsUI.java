    // Method to load data into JTable
    private void loadTableData() {
     // Get the table model from the designed table
     javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tableDentists.getModel();
     model.setRowCount(0); // Clear existing rows

     java.util.List<Object[]> list = dentistController.getDentistsList();
     for (Object[] row : list) {
         model.addRow(row);
     }
 }

