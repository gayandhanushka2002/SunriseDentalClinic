    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        
        int selectedRow = tableAppointments.getSelectedRow();

        if (selectedRow == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please select an appointment from the table to delete!", "Warning", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

            String apptNo = tableModel.getValueAt(selectedRow, 0).toString();

            int confirm = javax.swing.JOptionPane.showConfirmDialog(this, 
                    "Are you sure you want to cancel Appointment No: " + apptNo + "?", 
                    "Confirm Deletion", 
                    javax.swing.JOptionPane.YES_NO_OPTION);

            if (confirm == javax.swing.JOptionPane.YES_OPTION) {
                boolean isDeleted = apptController.deleteAppointment(apptNo);

                if (isDeleted) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Appointment cancelled successfully!", "Success", javax.swing.JOptionPane.INFORMATION_MESSAGE);
                    loadTableData(""); 
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Failed to cancel appointment. It might have existing bills.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
                }
            }
    }//GEN-LAST:event_btnDeleteActionPerformed

