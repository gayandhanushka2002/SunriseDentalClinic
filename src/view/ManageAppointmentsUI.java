    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        
            int selectedRow = tableAppointments.getSelectedRow();

            if (selectedRow == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please select an appointment from the table to update!", "Warning", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        String apptNo = tableModel.getValueAt(selectedRow, 0).toString();
        String currentDate = tableModel.getValueAt(selectedRow, 4).toString();
        String currentTime = tableModel.getValueAt(selectedRow, 5).toString();

        javax.swing.JTextField txtNewDate = new javax.swing.JTextField(currentDate);
        javax.swing.JTextField txtNewTime = new javax.swing.JTextField(currentTime);

        javax.swing.JPanel panel = new javax.swing.JPanel(new java.awt.GridLayout(2, 2, 10, 10));
        panel.add(new javax.swing.JLabel("New Date (YYYY-MM-DD):"));
        panel.add(txtNewDate);
        panel.add(new javax.swing.JLabel("New Time (HH:MM:SS):"));
        panel.add(txtNewTime);

        int result = javax.swing.JOptionPane.showConfirmDialog(this, panel, "Update Appointment: " + apptNo, javax.swing.JOptionPane.OK_CANCEL_OPTION, javax.swing.JOptionPane.PLAIN_MESSAGE);

            if (result == javax.swing.JOptionPane.OK_OPTION) {
            String newDate = txtNewDate.getText().trim();
            String newTime = txtNewTime.getText().trim();

        boolean isUpdated = apptController.updateAppointment(apptNo, newDate, newTime);

            if (isUpdated) {
             javax.swing.JOptionPane.showMessageDialog(this, "Appointment updated successfully!", "Success", javax.swing.JOptionPane.INFORMATION_MESSAGE);
                loadTableData(""); 
        }    else {
            javax.swing.JOptionPane.showMessageDialog(this, "Failed to update appointment. Check date/time format.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
       }
    }//GEN-LAST:event_btnUpdateActionPerformed

