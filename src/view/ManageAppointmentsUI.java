    private void loadTableData(String keyword) {
        tableModel.setRowCount(0); 
        java.util.List<Object[]> records = apptController.getAppointmentsList(keyword);
        
        for (Object[] row : records) {
            tableModel.addRow(row); // load to table
        }
    }

